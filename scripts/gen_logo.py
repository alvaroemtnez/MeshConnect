"""Logo concept B geometry -> SVG path data for the Android vectors (docs/logo.md).

Needs shapely: python3 -m venv /tmp/v && /tmp/v/bin/pip install shapely && /tmp/v/bin/python scripts/gen_logo.py
Writes the four drawables (launcher foreground and monochrome, two status-bar icons).
"""
from shapely.geometry import Point, LineString, Polygon, box
from shapely.ops import unary_union
import shapely.affinity as aff

def rrect(x, y, w, h, r):
    return box(x + r, y + r, x + w - r, y + h - r).buffer(r, quad_segs=16)

def bubble(scale):
    # Geometry drawn on the 24 grid, scaled for the 108 grid.
    body = rrect(3, 3.5, 18, 14.5, 4)
    tail = Polygon([(6.2, 16.5), (5.5, 21.5), (11, 17.6)])
    b = unary_union([body, tail])
    pts = [(7.5, 14), (12, 9.5), (16.5, 14)]
    holes = unary_union([Point(p).buffer(2.05, quad_segs=16) for p in pts] +
                        [LineString(pts).buffer(0.8, cap_style=1, join_style=1)])
    g = b.difference(holes)
    return aff.scale(g, scale, scale, origin=(0, 0))

def path(geom, dx=0, dy=0):
    out = []
    polys = [geom] if geom.geom_type == "Polygon" else list(geom.geoms)
    for p in polys:
        for ring in [p.exterior] + list(p.interiors):
            c = list(ring.coords)
            out.append("M" + " L".join(f"{x+dx:.2f},{y+dy:.2f}" for x, y in c[:-1]) + "Z")
    return "".join(out)

from pathlib import Path

RES = Path(__file__).resolve().parents[1] / "androidApp" / "src" / "main" / "res" / "drawable"
TEMPLATE = """<?xml version="1.0" encoding="utf-8"?>
<!-- {comment}
     Logo concept B "Mesh bubble". Generated by scripts/gen_logo.py (shapely);
     see docs/logo.md. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:tools="http://schemas.android.com/tools"
    android:width="{size}dp"
    android:height="{size}dp"
    android:viewportWidth="{size}"
    android:viewportHeight="{size}">
    <path
        android:fillColor="#FFFFFFFF"
        android:fillType="evenOdd"
        android:pathData="{d}"
        tools:ignore="VectorPath" />
</vector>
"""


def write(name, size, d, comment):
    # Two rings: the bubble outline and the one connected cut-out.
    if not d.startswith("M") or d.count("Z") < 2 or len(d) < 500:
        raise SystemExit(f"{name}: suspicious path data")
    (RES / f"{name}.xml").write_text(TEMPLATE.format(size=size, d=d, comment=comment))
    print(f"{name}.xml  ({len(d)} chars)")


tray = path(bubble(1))
g = bubble(52 / 18)
minx, miny, maxx, maxy = g.bounds
fg = path(g, 54 - (minx + maxx) / 2, 54 - (miny + maxy) / 2)
write("ic_launcher_foreground", 108, fg, "Launcher foreground: white bubble, mesh cut out to the background.")
write("ic_launcher_monochrome", 108, fg, "Themed-icon (Android 13+) layer: the launcher tints this silhouette.")
write("ic_stat_message", 24, tray, "Status-bar icon for messages. The system uses only its alpha channel.")
write("ic_stat_link", 24, tray, "Status-bar icon for the connection service. Alpha channel only.")
