#!/usr/bin/env python3
"""Write res/values{,-es,-ca}/strings.xml from one table: English (default),
Spanish and Valencian (values-ca, AVL forms) side by side, so the three stay
in step. Adapted from Skypost.

    python3 scripts/gen_strings.py

Add or change a string here, never in the XML files. Keys are grouped by
screen with a prefix (about_, chat_, nodes_...). Use %1$s / %1$d for
arguments and P for plurals.
"""

import pathlib
import sys
from xml.sax.saxutils import escape

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from strings_table import S, P, A  # noqa: E402

# Android plural categories: en one/other; es one/many/other; ca one/many/other.
CATS = {0: ["one", "other"], 1: ["one", "many", "other"], 2: ["one", "many", "other"]}
DIRS = {0: "values", 1: "values-es", 2: "values-ca"}
NOTE = {0: "English (default)", 1: "Spanish", 2: "Valencian (Catalan)"}
UNTRANSLATABLE = {"app_name", "app_name_full"}


def esc(t: str) -> str:
    t = escape(t).replace("'", "\\'").replace('"', '\\"')
    if t.startswith("@") or t.startswith("?"):
        t = "\\" + t
    return t


def main() -> None:
    for k, v in S.items():
        if len(v) != 3:
            raise SystemExit(f"{k}: needs (en, es, ca)")
    root = pathlib.Path(__file__).resolve().parents[1] / "androidApp" / "src" / "main" / "res"
    for i in range(3):
        out = [
            '<?xml version="1.0" encoding="utf-8"?>',
            f"<!-- {NOTE[i]}. Generated by scripts/gen_strings.py from scripts/strings_table.py; do not edit. -->",
            "<resources>",
        ]
        for k, v in S.items():
            if k in UNTRANSLATABLE:
                if i != 0:
                    continue
                out.append(f'    <string name="{k}" translatable="false">{esc(v[0])}</string>')
                continue
            fmt = ' formatted="false"' if "%" in v[i] and "%1$" not in v[i] and "%%" not in v[i] else ""
            out.append(f'    <string name="{k}"{fmt}>{esc(v[i])}</string>')
        for k, v in P.items():
            one, other = v[i]
            out.append(f'    <plurals name="{k}">')
            for c in CATS[i]:
                out.append(f'        <item quantity="{c}">{esc(one if c == "one" else other)}</item>')
            out.append("    </plurals>")
        for k, items in A.items():
            out.append(f'    <string-array name="{k}">')
            for it in items:
                out.append("        <item>" + esc(it[i]) + "</item>")
            out.append("    </string-array>")
        out.append("</resources>")
        d = root / DIRS[i]
        d.mkdir(exist_ok=True)
        (d / "strings.xml").write_text("\n".join(out) + "\n")
        print(d / "strings.xml", len(S), "strings")


if __name__ == "__main__":
    main()
